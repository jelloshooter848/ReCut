#!/usr/bin/env node
/**
 * Regenerates the npm section of THIRD_PARTY_NOTICES.md: every package ReCut ships at run time, i.e. the
 * package.json "dependencies" and their own dependencies (electron-builder copies them into the app, and Vite /
 * esbuild bundle their code into dist/), with version, licence and the licence text from node_modules.
 *
 *   node scripts/third-party-notices.mjs           rewrite the section between the npm-packages markers
 *   node scripts/third-party-notices.mjs --check   exit 1 if the file is out of date (tests/unit/licences.test.ts)
 *
 * Run it after adding, removing or upgrading a runtime dependency (after `npm ci`). No dependencies of its own.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const NOTICES = path.join(root, 'THIRD_PARTY_NOTICES.md');
const START = '<!-- npm-packages:start (generated by scripts/third-party-notices.mjs; do not edit by hand) -->';
const END = '<!-- npm-packages:end -->';
const LICENCE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

function readJson(p) { return JSON.parse(fs.readFileSync(p, 'utf8')); }

/** Directory of package `name` as Node would resolve it from `fromDir` (nested node_modules first, then upwards). */
function resolvePackageDir(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function licenceOf(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license && typeof pkg.license.type === 'string') return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? l).join(' OR ');
  return 'UNKNOWN';
}

function repoOf(pkg) {
  const r = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  const url = r ? r.replace(/^git\+/, '').replace(/\.git$/, '').replace(/^git:\/\//, 'https://') : pkg.homepage;
  if (!url) return '';
  if (/^[\w.-]+\/[\w.-]+$/.test(url)) return `https://github.com/${url}`; // npm shorthand owner/repo
  return url.replace(/^github:/, 'https://github.com/');
}

/** The runtime package closure: [{ name, version, licence, repo, licenceText }], sorted by name. */
export function collectRuntimePackages(projectRoot = root) {
  const top = readJson(path.join(projectRoot, 'package.json'));
  const seen = new Map();
  const queue = Object.keys(top.dependencies ?? {}).map((name) => ({ name, from: projectRoot, optional: false }));
  // The Electron runtime itself (a devDependency, but its binaries are the app). Its own npm dependencies only
  // download it at install time and are not shipped, so they are not walked.
  queue.push({ name: 'electron', from: projectRoot, optional: false, leaf: true });
  while (queue.length) {
    const { name, from, optional, leaf } = queue.shift();
    const dir = resolvePackageDir(name, from);
    if (!dir) {
      if (optional) continue;
      throw new Error(`runtime dependency ${name} is not installed (run npm ci)`);
    }
    const key = fs.realpathSync(dir);
    if (seen.has(key)) continue;
    const pkg = readJson(path.join(dir, 'package.json'));
    const files = fs.readdirSync(dir).filter((f) => LICENCE_FILE.test(f)).sort();
    const licenceText = files.map((f) => fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim()).join('\n\n');
    seen.set(key, { name: pkg.name ?? name, version: pkg.version ?? '', licence: licenceOf(pkg), repo: repoOf(pkg), licenceText });
    if (leaf) continue;
    for (const dep of Object.keys(pkg.dependencies ?? {})) queue.push({ name: dep, from: dir, optional: false });
    for (const dep of Object.keys(pkg.optionalDependencies ?? {})) queue.push({ name: dep, from: dir, optional: true });
    // Required peer dependencies are shipped too (e.g. react for react-dom). Optional peers (peerDependenciesMeta)
    // are not: zustand's optional @types/react is a type package, and its immer / react are top-level dependencies.
    for (const dep of Object.keys(pkg.peerDependencies ?? {})) {
      if (!pkg.peerDependenciesMeta?.[dep]?.optional) queue.push({ name: dep, from: dir, optional: false });
    }
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

export function renderNpmSection(pkgs) {
  const out = [START, '', '| Package | Version | Licence | Source |', '|---|---|---|---|'];
  for (const p of pkgs) out.push(`| ${p.name} | ${p.version} | ${p.licence} | ${p.repo || '(none listed)'} |`);
  for (const p of pkgs) {
    out.push('', `#### ${p.name} ${p.version} (${p.licence})`, '');
    if (p.licenceText) out.push('```text', p.licenceText, '```');
    else out.push(`No licence file in the package; package.json declares \`${p.licence}\`.`);
  }
  out.push('', END);
  return out.join('\n');
}

/** THIRD_PARTY_NOTICES.md text with the npm section regenerated (line endings normalized to \n). */
export function regenerate(current, pkgs) {
  const text = current.replace(/\r\n/g, '\n');
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error(`THIRD_PARTY_NOTICES.md has no ${START} ... ${END} section`);
  return text.slice(0, a) + renderNpmSection(pkgs) + text.slice(b + END.length);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const current = fs.readFileSync(NOTICES, 'utf8');
  const next = regenerate(current, collectRuntimePackages());
  if (process.argv.includes('--check')) {
    if (next !== current.replace(/\r\n/g, '\n')) {
      console.error('THIRD_PARTY_NOTICES.md is out of date: run node scripts/third-party-notices.mjs');
      process.exit(1);
    }
    console.log('THIRD_PARTY_NOTICES.md is up to date');
  } else {
    fs.writeFileSync(NOTICES, next);
    console.log(`THIRD_PARTY_NOTICES.md: ${collectRuntimePackages().length} npm packages`);
  }
}
