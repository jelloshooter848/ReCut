/** Base URL of the pinned language files; a file's URL is `TESSDATA_BASE + file`. */
export const TESSDATA_BASE = `https://raw.githubusercontent.com/tesseract-ocr/tessdata_fast/${TESSDATA_COMMIT}/`;

/** One installable OCR language. */
export interface OcrLanguageInfo {
  /** tessdata code (`eng`, `chi_sim`, ...), also the file stem. */
  code: string;
  /** English display name. */
  name: string;
  /** File name under TESSDATA_BASE and in the local tessdata folder (`<code>.traineddata`). */
  file: string;
  /** Exact size in bytes. */
  bytes: number;
  /** Lower-case hex SHA-256 of the file. */
  sha256: string;
}

