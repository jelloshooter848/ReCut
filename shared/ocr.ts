/** Region / script subtags that pick traditional Chinese. */
const CHI_TRA_HINTS = new Set(['hant', 'tw', 'hk', 'mo']);

/**
 * Best tessdata code for a track language tag (`fre`, `fr`, `fr-CA`, `zh-Hant`, `chi`, ...), or null when the
 * tag is missing, undetermined (`und`, `unknown`, `mis`, `mul`, `zxx`) or names a language not in OCR_LANGUAGES.
 */
export function guessOcrLanguage(tag?: string | null): string | null {
  if (typeof tag !== 'string') return null;
  const parts = tag.trim().toLowerCase().split(/[-_]/).filter(Boolean);
  if (parts.length === 0) return null;
  const [primary, ...rest] = parts;
  // A full tessdata code with an underscore (chi_sim, srp_latn) given as-is.
  const whole = parts.join('_');
  if (BY_CODE.has(whole)) return whole;
  let code = BY_CODE.has(primary) ? primary : TAG_TO_TESSDATA[primary];
  if (!code) return null;
  if (code === 'chi_sim' && rest.some((p) => CHI_TRA_HINTS.has(p))) code = 'chi_tra';
  if (code === 'srp' && rest.includes('latn')) code = 'srp_latn';
  return BY_CODE.has(code) ? code : null;
}

/** tessdata codes whose ISO 639-2/B tag differs from the code (or which have no 3-letter code of their own). */
const TESSDATA_TO_ISO6392B: Record<string, string> = {
  fra: 'fre', deu: 'ger', nld: 'dut', ces: 'cze', ell: 'gre', ron: 'rum', slk: 'slo', fas: 'per', isl: 'ice',
  mkd: 'mac', msa: 'may', sqi: 'alb', hye: 'arm', eus: 'baq', kat: 'geo', cym: 'wel', mya: 'bur', bod: 'tib',
  chi_sim: 'chi', chi_tra: 'chi', srp_latn: 'srp',
};

/**
 * ISO 639-2/B language tag for a track read with tessdata `code` (what Matroska and ffprobe use): `fra` → `fre`,
 * `chi_sim` → `chi`; codes that are already 639-2 come back unchanged.
 */
export function iso6392ForOcr(code: string): string {
  return TESSDATA_TO_ISO6392B[code] ?? code.split('_')[0];
}

/** Start OCR of one bitmap subtitle stream (runs as a job of kind 'ocr'). */
export interface OcrRequest {
  mediaId: ID;
  /** Source media file. */
  path: string;
  /** Absolute ffprobe stream index of the bitmap subtitle stream. */
  streamIndex: number;
  /** tessdata code from OCR_LANGUAGES; must be installed. */
  language: string;
  /** The stream's codec as probed (informational; the job probes it again). */
  codec?: string;
}

/** `JobInfo.result` of a finished 'ocr' job. */
export interface OcrResult {
  mediaId: ID;
  streamIndex: number;
  language: string;
  codec: string;
  /** Recognized cues, source seconds. */
  cues: SubtitleCue[];
  /** Number of subtitle events (images) read from the stream. */
  events: number;
  /** True when the result came from the OCR cache instead of a new run. */
  cached: boolean;
}

/** One row of `ocrLanguages()`: a manifest language and whether it is installed. */
export interface OcrLanguageState {
  code: string;
  name: string;
  bytes: number;
  /** The file is in the OCR data folder with the manifest size. */
  installed: boolean;
  /** Id of the running or queued 'download' job installing it, if any. */
  jobId?: string;
}
