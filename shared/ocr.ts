const BY_CODE = new Map<string, OcrLanguageInfo>(OCR_LANGUAGES.map((l) => [l.code, l]));

/** The manifest entry for a tessdata code, or undefined when it is not installable. */
export function ocrLanguage(code: string | undefined | null): OcrLanguageInfo | undefined {
  return typeof code === 'string' ? BY_CODE.get(code) : undefined;
}

export function isOcrLanguageCode(code: unknown): code is string {
  return typeof code === 'string' && BY_CODE.has(code);
}

/** Download URL of a manifest language. */
export function ocrLanguageUrl(lang: OcrLanguageInfo): string {
  return TESSDATA_BASE + lang.file;
}

